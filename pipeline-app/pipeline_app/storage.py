"""Per-job filesystem layout helpers."""
from __future__ import annotations

import json
import re
import shutil
import time
import uuid
from dataclasses import dataclass
from pathlib import Path

from .config import JOBS_DIR


@dataclass
class JobPaths:
    root: Path
    input_video: Path
    frames_dir: Path           # raw ffmpeg-extracted frames
    cubemap_dir: Path          # 6×N cubemap faces (ERP videos only)
    workspace_dir: Path
    splat_ply: Path            # full OpenSplat output
    splat_sog: Path            # compressed SOG (lazy: only after user clicks convert)
    settings_json: Path
    logs_dir: Path
    status_json: Path

    @classmethod
    def for_job(cls, job_id: str) -> "JobPaths":
        root = JOBS_DIR / job_id
        return cls(
            root=root,
            input_video=root / "input.mp4",
            frames_dir=root / "frames",
            cubemap_dir=root / "cubemap",
            workspace_dir=root / "workspace",
            splat_ply=root / "splat.ply",
            splat_sog=root / "splat.sog",
            settings_json=root / "settings.json",
            logs_dir=root / "logs",
            status_json=root / "status.json",
        )


def new_job_id() -> str:
    return uuid.uuid4().hex


def init_job_dir(job_id: str) -> JobPaths:
    paths = JobPaths.for_job(job_id)
    paths.root.mkdir(parents=True, exist_ok=True)
    paths.frames_dir.mkdir(exist_ok=True)
    paths.workspace_dir.mkdir(exist_ok=True)
    paths.logs_dir.mkdir(exist_ok=True)
    return paths


def save_upload(video_bytes, dest: Path) -> None:
    """Write uploaded video bytes atomically (via temp + rename)."""
    tmp = dest.with_suffix(dest.suffix + ".part")
    with open(tmp, "wb") as f:
        f.write(video_bytes)
    tmp.replace(dest)


def write_status(paths: JobPaths, **fields) -> None:
    """Update job state in status.json. Merges with existing fields so
    immutable config (fps, scale, opensplat_iters) survives progress writes."""
    existing = read_status(paths)
    payload = {**existing, **fields, "updated_at": time.time()}
    tmp = paths.status_json.with_suffix(".json.part")
    tmp.write_text(json.dumps(payload, default=str, indent=2))
    tmp.replace(paths.status_json)


def read_status(paths: JobPaths) -> dict:
    if not paths.status_json.exists():
        return {}
    return json.loads(paths.status_json.read_text())


def read_ply_iteration_count(paths: JobPaths) -> Optional[int]:
    """Read the iteration count from an OpenSplat .ply header.

    OpenSplat writes `comment Generated by opensplat at iteration N` as
    the second line of the .ply. Returns None if not present.
    """
    if not paths.splat_ply.is_file():
        return None
    try:
        with open(paths.splat_ply, "rb") as f:
            # Read just the first 8 lines; safe even for multi-GB files.
            for _ in range(8):
                line = f.readline().decode("ascii", errors="replace").strip()
                if "at iteration" in line:
                    # e.g. "comment Generated by opensplat at iteration 10000"
                    parts = line.rsplit(" ", 1)
                    return int(parts[-1])
    except (OSError, ValueError):
        return None
    return None


def read_ply_aabb(paths: JobPaths) -> Optional[dict]:
    """Compute the axis-aligned bounding box of a .ply file.

    Reads the binary vertex data (little-endian float32, 62 floats per vertex)
    and returns {center: [x,y,z], half_extents: [hx,hy,hz]} in COLMAP local frame.
    Returns None if the file is missing or unreadable.
    """
    if not paths.splat_ply.is_file():
        return None
    try:
        import struct
        _FLOATS_PER_VERTEX = 62
        _VERTEX_SIZE = _FLOATS_PER_VERTEX * 4  # 248 bytes

        with open(paths.splat_ply, "rb") as f:
            header_done = False
            vertex_count = 0
            min_xyz = [float("inf")] * 3
            max_xyz = [float("-inf")] * 3
            while True:
                line = f.readline()
                if not line:
                    break
                line = line.decode("ascii", errors="replace").strip()
                if line.lower().startswith("element vertex"):
                    vertex_count = int(line.split()[-1])
                if line.lower() == "end_header":
                    header_done = True
                    break
            if not header_done or vertex_count == 0:
                return None
            # Read all vertex positions (first 3 floats = x,y,z)
            for _ in range(vertex_count):
                chunk = f.read(_VERTEX_SIZE)
                if len(chunk) < _VERTEX_SIZE:
                    break
                x, y, z = struct.unpack_from("<3f", chunk, 0)
                for i, v in enumerate((x, y, z)):
                    if v < min_xyz[i]:
                        min_xyz[i] = v
                    if v > max_xyz[i]:
                        max_xyz[i] = v
        if min_xyz[0] == float("inf"):
            return None
        cx = (min_xyz[0] + max_xyz[0]) / 2
        cy = (min_xyz[1] + max_xyz[1]) / 2
        cz = (min_xyz[2] + max_xyz[2]) / 2
        hx = (max_xyz[0] - min_xyz[0]) / 2
        hy = (max_xyz[1] - min_xyz[1]) / 2
        hz = (max_xyz[2] - min_xyz[2]) / 2
        return {
            "center": [cx, cy, cz],
            "half_extents": [hx, hy, hz],
            "vertex_count": vertex_count,
        }
    except (OSError, ValueError, struct.error):
        return None


def build_export_html(template_path: Path, paths: JobPaths) -> str:
    """Generate a self-contained HTML for a job by inlining its SOG into
    the single-file SuperSplat template.

    The template's `sse-bootstrap` script tag contains a JSON with `contentUrl`
    pointing at a `data:application/octet-stream;base64,...` URI. We:
      1. base64-encode the job's splat.sog
      2. replace that data URI with our new one
      3. optionally splice in the job's settings.json (camera position, FOV,
         post-effect settings) into the bootstrap JSON's "settings" field
    """
    template = template_path.read_text(encoding="utf-8")

    # 1. Encode the job's SOG.
    sog_bytes = paths.splat_sog.read_bytes()
    sog_b64 = _b64encode(sog_bytes)
    new_content_url = f"data:application/octet-stream;base64,{sog_b64}"

    # 2. Replace the existing inlined data URI.
    #    Pattern: the URI is inside JSON-escaped quotes; we match a bounded
    #    data URI starting with the octet-stream prefix.
    pattern = re.compile(r'data:application/octet-stream;base64,[A-Za-z0-9+/=]+')
    new_template, n_repl = pattern.subn(new_content_url, template, count=1)
    if n_repl == 0:
        raise RuntimeError(
            "Template does not contain an inlined SOG data URI; "
            "cannot substitute. Was the template built differently?"
        )

    # 3. Optionally splice the job's settings.json into "settings" field.
    if paths.settings_json.is_file():
        try:
            user_settings = json.loads(paths.settings_json.read_text())
        except Exception:
            user_settings = None
        if user_settings:
            # Find the bootstrap JSON and update its "settings" field.
            boot_re = re.compile(
                r'(<script type="application/json" id="sse-bootstrap">)(\{.*?\})(</script>)',
                re.DOTALL,
            )
            def _patch(m: re.Match[str]) -> str:
                head, blob, tail = m.group(1), m.group(2), m.group(3)
                try:
                    cfg = json.loads(blob)
                except Exception:
                    return m.group(0)
                cfg["settings"] = user_settings
                return head + json.dumps(cfg) + tail
            new_template, n = boot_re.subn(_patch, new_template, count=1)
            if n == 0:
                # Couldn't patch (no bootstrap block); that's fine.
                pass

    return new_template


def _b64encode(b: bytes) -> str:
    """Local import shim for base64 (keeps the top of storage.py dependency-light)."""
    import base64
    return base64.b64encode(b).decode("ascii")